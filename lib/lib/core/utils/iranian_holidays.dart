/// تعطیلات رسمی ایران — شمسی ثابت + قمری هاردکد شده برای ۱۴۰۳ و ۱۴۰۴
class IranianHolidays {
  /// تعطیلات شمسی ثابت (ماه/روز جلالی)
  static const _fixedJalali = <String, String>{
    '01/01': 'نوروز',
    '01/02': 'نوروز',
    '01/03': 'نوروز',
    '01/04': 'نوروز',
    '01/12': 'روز جمهوری اسلامی',
    '01/13': 'سیزده‌به‌در',
    '03/14': 'رحلت امام خمینی(ره)',
    '03/15': 'قیام ۱۵ خرداد',
    '11/22': 'پیروزی انقلاب اسلامی',
    '12/29': 'ملی شدن صنعت نفت',
  };

  /// تعطیلات قمری با تاریخ میلادی (سال ۱۴۰۳ و ۱۴۰۴)
  static const _gregorianFixed = <String, String>{
    // ۱۴۰۳
    '2024-04-10': 'عید فطر',
    '2024-04-11': 'عید فطر',
    '2024-06-17': 'عید قربان',
    '2024-06-18': 'عید قربان',
    '2024-06-27': 'عید غدیر',
    '2024-07-15': 'تاسوعا',
    '2024-07-16': 'عاشورا',
    '2024-08-24': 'اربعین',
    '2024-09-14': 'رحلت پیامبر(ص)',
    '2024-09-15': 'شهادت امام حسن(ع)',
    '2024-09-18': 'شهادت امام رضا(ع)',
    '2024-11-22': 'میلاد پیامبر(ص) و امام صادق(ع)',
    '2024-12-03': 'شهادت حضرت فاطمه(س)',
    // ۱۴۰۴
    '2025-03-30': 'عید فطر',
    '2025-03-31': 'عید فطر',
    '2025-06-06': 'عید قربان',
    '2025-06-07': 'عید قربان',
    '2025-06-16': 'عید غدیر',
    '2025-07-04': 'تاسوعا',
    '2025-07-05': 'عاشورا',
    '2025-08-13': 'اربعین',
    '2025-09-03': 'رحلت پیامبر(ص)',
    '2025-09-04': 'شهادت امام حسن(ع)',
    '2025-09-07': 'شهادت امام رضا(ع)',
    '2025-11-12': 'میلاد پیامبر(ص) و امام صادق(ع)',
    '2025-12-03': 'شهادت حضرت فاطمه(س)',
    '2026-01-21': 'میلاد امیرالمؤمنین(ع)',
    '2026-02-04': 'مبعث پیامبر(ص)',
    '2026-03-20': 'ملی شدن صنعت نفت',
  };

  /// بررسی تعطیلی — ورودی: تاریخ میلادی ISO (YYYY-MM-DD) + ماه/روز جلالی
  static String? holidayName(String gregorianIso, int jalaliMonth, int jalaliDay) {
    // قمری
    final gKey = gregorianIso.substring(0, 10);
    if (_gregorianFixed.containsKey(gKey)) return _gregorianFixed[gKey];
    // شمسی ثابت
    final jKey =
        '${jalaliMonth.toString().padLeft(2, '0')}/${jalaliDay.toString().padLeft(2, '0')}';
    return _fixedJalali[jKey];
  }

  static bool isHoliday(String gregorianIso, int jalaliMonth, int jalaliDay) =>
      holidayName(gregorianIso, jalaliMonth, jalaliDay) != null;
}
